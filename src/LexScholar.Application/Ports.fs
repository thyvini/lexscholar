namespace LexScholar.Application

open System
open System.IO
open System.Threading
open System.Threading.Tasks
open LexScholar.Domain

// For every stream-opening capability, successful task completion transfers
// ownership even if cancellation raced with it. On a faulted or cancelled task,
// no stream is transferred and the provider must release acquired resources.

/// Opens a document's stored original read-only by UUID, without assuming a
/// viewer. Returns DocumentNotFound for an unknown UUID and DocumentUnavailable
/// unless the original exists, is readable and its length equals the recorded
/// byte length. Content is not rehashed or reparsed on open, so same-length
/// changes made outside LexScholar are not detected (see research.md, "Document
/// availability on open"). On success the caller owns the returned stream and
/// must dispose it; on cancellation or failure before success the provider
/// disposes its resources. The token covers opening; callers pass a token to
/// later reads.
type OpenVerifiedContent = Guid -> CancellationToken -> Task<Result<VerifiedContent, ContentFailure>>

// Staging capabilities take a StagingKey generated by the import workflow, never
// a user-supplied path or filename. No import state is persisted: startup
// cleanup deletes whatever staging files a crash leaves behind.

/// Create and open only this import's staging file for writing, never a
/// published original. A successful return transfers the stream to the caller,
/// who must dispose it before validation or promotion; if opening fails or is
/// cancelled, the provider must dispose any resources it acquired. The token
/// covers opening; callers pass a token to subsequent stream writes.
type OpenStagedWrite = StagingKey -> CancellationToken -> Task<Stream>

/// Open the import's staged bytes read-only for streamed validation/comparison.
/// The caller owns and disposes a successfully returned stream, including when
/// later reads fail or are cancelled. The provider cleans up on failed opening.
/// The token covers opening; callers pass a token to subsequent stream reads.
type OpenStagedRead = StagingKey -> CancellationToken -> Task<Stream>

/// Promote validated, flushed staged bytes to a newly generated storage key and
/// return that key. The original is made read-only and moved without
/// overwriting on the same filesystem; an existing original is never mutated.
type PromoteStagedContent = StagingKey -> CancellationToken -> Task<string>

/// Delete only this import's staging file, never a committed original or
/// another import's file. Succeeds if the file no longer exists.
type DiscardStagedContent = StagingKey -> CancellationToken -> Task<unit>

/// Open a stored original read-only by its storage key, for exact byte
/// comparison during import. The caller owns and disposes the returned stream.
type OpenStoredOriginal = string -> CancellationToken -> Task<Stream>

/// Documents whose SHA-256 equals the given lowercase hex digest. The digest
/// only narrows candidates; equality is decided by comparing bytes.
type FindDocumentsBySha256 = string -> CancellationToken -> Task<LibraryDocument list>

/// Insert a new library document row.
/// A fault does not prove the row was not committed. Callers must not delete
/// promoted bytes on that assumption; startup checks actual row references.
type InsertDocument = LibraryDocument -> CancellationToken -> Task<unit>
